"""
Ablation Comparison Report
===========================
This script compares Zero, Mean, Resample, and ACDC side by side using the
existing JSON result files generated by the standalone ablation scripts.

Outputs:
- Code/ablation_comparison_summary.csv
- Code/ablation_comparison_report.html
- Code/ablation_comparison_figure.png
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from statistics import mean, median, pstdev
from typing import Any, Dict, List, Tuple

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns


ROOT = Path(__file__).resolve().parent
ZERO_RESULTS = ROOT / "zero_ablation" / "zero_ablation_results.json"
MEAN_RESULTS = ROOT / "mean_ablation" / "mean_ablation_results.json"
RESAMPLE_RESULTS = ROOT / "resample_ablation" / "resample_ablation_results.json"
ACDC_RESULTS = ROOT / "acdc_svn_results" / "acdc_results.json"


@dataclass(frozen=True)
class AblationSummary:
    method: str
    total_records: int
    mean_drop: float
    median_drop: float
    std_drop: float
    min_drop: float
    max_drop: float
    top_head: str
    top_head_drop: float
    layer_of_top_head: int
    num_positive: int
    num_negative: int


def load_json(path: Path) -> List[Dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing result file: {path}")
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
        # Handle the refactored case where results are saved within 'valid_ablations'
        if isinstance(data, dict) and "valid_ablations" in data:
            return data["valid_ablations"]
        return data


def get_drop_key(rows: List[Dict[str, Any]]) -> str:
    sample = rows[0]
    if "avg_performance_drop" in sample:
        return "avg_performance_drop"
    return "performance_drop"


def summarize_method(method: str, rows: List[Dict[str, Any]]) -> AblationSummary:
    drop_key = get_drop_key(rows)
    drops = [float(row[drop_key]) for row in rows]

    head_scores: Dict[Tuple[int, int], List[float]] = {}
    for row in rows:
        key = (int(row["layer"]), int(row["head"]))
        head_scores.setdefault(key, []).append(float(row[drop_key]))

    head_means = {key: mean(values) for key, values in head_scores.items()}
    best_layer, best_head = max(head_means, key=head_means.get)
    best_drop = head_means[(best_layer, best_head)]

    return AblationSummary(
        method=method,
        total_records=len(rows),
        mean_drop=float(mean(drops)),
        median_drop=float(median(drops)),
        std_drop=float(pstdev(drops)),
        min_drop=float(min(drops)),
        max_drop=float(max(drops)),
        top_head=f"L{best_layer}H{best_head}",
        top_head_drop=float(best_drop),
        layer_of_top_head=int(best_layer),
        num_positive=sum(1 for value in drops if value > 0),
        num_negative=sum(1 for value in drops if value < 0),
    )


def build_comparison_frame(summaries: List[AblationSummary]) -> pd.DataFrame:
    return pd.DataFrame(
        [
            {
                "Method": summary.method,
                "Records": summary.total_records,
                "Mean Drop": summary.mean_drop,
                "Median Drop": summary.median_drop,
                "Std Dev": summary.std_drop,
                "Min Drop": summary.min_drop,
                "Max Drop": summary.max_drop,
                "Top Head": summary.top_head,
                "Top Head Drop": summary.top_head_drop,
                "Top Head Layer": summary.layer_of_top_head,
                "Positive Count": summary.num_positive,
                "Negative Count": summary.num_negative,
            }
            for summary in summaries
        ]
    )


def make_figure(df: pd.DataFrame, output_path: Path) -> None:
    sns.set_style("whitegrid")
    plt.rcParams["figure.figsize"] = (16, 10)

    methods = df["Method"].tolist()
    colors = ["#2ecc71", "#9b59b6", "#e74c3c", "#3498db"]

    fig, axes = plt.subplots(2, 2, figsize=(16, 10))
    fig.suptitle("Subject-Verb Agreement Ablation Comparison", fontsize=18, fontweight="bold")

    # Mean drop
    axes[0, 0].bar(methods, df["Mean Drop"], color=colors, edgecolor="black", linewidth=1.2)
    axes[0, 0].set_title("Mean Performance Drop")
    axes[0, 0].set_ylabel("Drop")
    axes[0, 0].axhline(0, color="black", linewidth=1)
    for idx, value in enumerate(df["Mean Drop"]):
        axes[0, 0].text(idx, value, f"{value:.3f}", ha="center", va="bottom" if value >= 0 else "top", fontsize=10)

    # Max drop
    axes[0, 1].bar(methods, df["Max Drop"], color=colors, edgecolor="black", linewidth=1.2)
    axes[0, 1].set_title("Maximum Performance Drop")
    axes[0, 1].set_ylabel("Drop")
    axes[0, 1].axhline(0, color="black", linewidth=1)
    for idx, value in enumerate(df["Max Drop"]):
        axes[0, 1].text(idx, value, f"{value:.3f}", ha="center", va="bottom", fontsize=10)

    # Top head drop
    axes[1, 0].bar(methods, df["Top Head Drop"], color=colors, edgecolor="black", linewidth=1.2)
    axes[1, 0].set_title("Top Head Mean Drop")
    axes[1, 0].set_ylabel("Drop")
    axes[1, 0].axhline(0, color="black", linewidth=1)
    for idx, value in enumerate(df["Top Head Drop"]):
        axes[1, 0].text(idx, value, f"{value:.3f}", ha="center", va="bottom", fontsize=10)

    # Layer of top head
    axes[1, 1].bar(methods, df["Top Head Layer"], color=colors, edgecolor="black", linewidth=1.2)
    axes[1, 1].set_title("Layer of Most Important Head")
    axes[1, 1].set_ylabel("Layer")
    axes[1, 1].set_xlabel("Method")
    for idx, value in enumerate(df["Top Head Layer"]):
        axes[1, 1].text(idx, value, f"L{int(value)}", ha="center", va="bottom", fontsize=10)

    for ax in axes.flat:
        ax.tick_params(axis="x", rotation=12)

    plt.tight_layout(rect=[0, 0.02, 1, 0.96])
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def html_table(df: pd.DataFrame) -> str:
    display_df = df.copy()
    for col in ["Mean Drop", "Median Drop", "Std Dev", "Min Drop", "Max Drop", "Top Head Drop"]:
        display_df[col] = display_df[col].map(lambda value: f"{value:.4f}")
    return display_df.to_html(index=False, escape=False)


def make_latex_table(df: pd.DataFrame, output_path: Path) -> None:
    """Generates a LaTeX table format suitable for a NeurIPS paper."""
    paper_df = df[["Method", "Mean Drop", "Max Drop", "Top Head", "Top Head Drop"]].copy()
    
    for col in ["Mean Drop", "Max Drop", "Top Head Drop"]:
        paper_df[col] = paper_df[col].apply(lambda x: f"{float(x):.4f}")
        
    latex_str = paper_df.to_latex(index=False)
    
    latex_env = f"""\\begin{{table}}[h]
\\centering
\\caption{{Comparison of Ablation Methods on Subject-Verb Number Agreement.}}
\\label{{tab:ablation_results}}
{latex_str}
\\end{{table}}
"""
    output_path.write_text(latex_env, encoding="utf-8")


