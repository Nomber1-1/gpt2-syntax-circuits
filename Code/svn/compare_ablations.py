def main() -> None:
    zero_rows = load_json(ZERO_RESULTS)
    mean_rows = load_json(MEAN_RESULTS)
    resample_rows = load_json(RESAMPLE_RESULTS)
    acdc_rows = load_json(ACDC_RESULTS)

    summaries = [
        summarize_method("Zero Ablation", zero_rows),
        summarize_method("Mean Ablation", mean_rows),
        summarize_method("Resample Ablation", resample_rows),
        summarize_method("ACDC Pruning", acdc_rows),
    ]

    df = build_comparison_frame(summaries)

    out_dir = ROOT / "compare_results"
    out_dir.mkdir(exist_ok=True)
    csv_path = out_dir / "ablation_comparison_summary.csv"
    figure_path = out_dir / "ablation_comparison_figure.png"
    html_path = out_dir / "ablation_comparison_report.html"
    latex_path = out_dir / "ablation_comparison_table.tex"

    df.to_csv(csv_path, index=False)
    make_figure(df, figure_path)
    make_html_report(df, figure_path, html_path)
    make_latex_table(df, latex_path)

    print("Comparison summary saved to", csv_path)
    print("Comparison figure saved to", figure_path)
    print("HTML report saved to", html_path)
    print("LaTeX table saved to", latex_path)
    print("\nSide-by-side summary:")
    print(df.to_string(index=False))


if __name__ == "__main__":
    main()
